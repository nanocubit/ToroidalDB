#!/bin/bash

echo "⏱️ Запуск бенчмарков ToroidalDB v3.1.0..."

echo ""
echo "📊 Тесты производительности:"
echo "  - Локальный поиск (1K, 10K, 100K, 1M узлов)"
echo "  - Распределённый поиск (3 шарда)"
echo "  - Агрегационные операции"
echo "  - Кэшированные vs некэшированные запросы"
echo "  - Ранняя остановка поиска"
echo "  - Транзакционные операции"

echo ""
echo "🔧 Подготовка к бенчмаркам..."

# Проверяем, установлен ли criterion
if command -v cargo &> /dev/null; then
    echo "✅ Cargo установлен"
    
    # Запускаем бенчмарки
    echo ""
    echo "🚀 Запуск бенчмарков..."
    cargo bench
    
    if [ $? -eq 0 ]; then
        echo ""
        echo "✅ Бенчмарки успешно выполнены!"
    else
        echo ""
        echo "❌ Ошибка выполнения бенчмарков"
        exit 1
    fi
else
    echo "❌ Cargo не установлен, невозможно запустить бенчмарки"
    exit 1
fi

echo ""
echo "📈 Результаты бенчмарков:"
echo "  - local_search_1000_nodes: время выполнения локального поиска"
echo "  - aggregation_count_1000_nodes: время выполнения агрегации COUNT"
echo "  - distributed_search_3_shards: время выполнения распределенного поиска"
echo "  - cached_search_vs_uncached: сравнение производительности кэширования"

echo ""
echo "💡 Рекомендации по производительности:"
echo "  - Используйте кэширование для часто повторяющихся запросов"
echo "  - Применяйте раннюю остановку при ограничении количества результатов"
echo "  - Используйте распределённое выполнение для больших наборов данных"
echo "  - Оптимизируйте размер векторов для лучшей производительности"
echo "  - Регулярно очищайте кэш для предотвращения переполнения памяти"